import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createToolExecutor, tools } from './fixtures/model-harness.js';

// Real CLI and stdio MCP, without a model, database, tmux, runtime or channel.
// Each executor receives only its own temporary environment; no live paths.
async function fixture(t) {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'model-tools-'));
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'model-outside-'));
  const home = path.join(root, 'home');
  fs.mkdirSync(home);
  const env = { PATH: process.env.PATH, HOME: home, ZYLOS_DIR: root,
    PM2_HOME: path.join(home, '.pm2'), CODEX_HOME: path.join(home, '.codex'),
    TMPDIR: path.join(root, 'tmp'), TMUX_TMPDIR: path.join(root, 'tmp'), TZ: 'UTC' };
  for (const directory of [env.PM2_HOME, env.CODEX_HOME, env.TMPDIR]) fs.mkdirSync(directory);
  let executor;
  t.after(async () => {
    try { await executor?.close(); } finally {
      fs.rmSync(root, { recursive: true, force: true });
      fs.rmSync(outside, { recursive: true, force: true });
    }
  });
  const f = { root, env, trace: [], snapshot: () => ({}) };
  executor = await createToolExecutor(f);
  const target = relative => path.join(root, 'memory', relative);
  const write = (relative, content) => {
    fs.mkdirSync(path.dirname(target(relative)), { recursive: true });
    fs.writeFileSync(target(relative), content);
  };
  const run = (args, extra = {}) => executor.execute({ name: 'run_script',
    arguments: { script: 'reference-index', args, ...extra } });
  return { ...f, outside, target, write, run };
}
const page = '# Fixture page\n<!-- zylos:entry kind=projects -->\n- **Status:** active\n- **Updated:** 2026-11-11\n- **Keys:** fixture\n\nExact fixture bytes.\n';

test('model tools advertise the reference index script', () => {
  assert.ok(tools.find(tool => tool.name === 'run_script').inputSchema.properties.script.enum.includes('reference-index'));
});

test('reference index rebuild runs the real CLI in the fixture environment', async t => {
  const f = await fixture(t);
  f.write('reference/projects/topic.md', page);
  f.write('references.md', '# References\n- Projects: reference/projects.md\n');
  f.write('reference/projects.md', '# Projects\nLegacy navigation remains valid.\n');
  const old = fs.readFileSync(f.target('reference/projects.md'));
  const navigation = fs.readFileSync(f.target('references.md'));
  const result = await f.run(['rebuild']);
  assert.equal(result.status, 0, JSON.stringify(result));
  assert.equal(JSON.parse(result.stdout).ok, true);
  for (const kind of ['projects', 'decisions']) for (const archive of ['', '/archive']) {
    assert.match(fs.readFileSync(f.target('reference/' + kind + archive + '/INDEX.md'), 'utf8'), /generated by reference-index/);
  }
  assert.match(fs.readFileSync(f.target('reference/projects/INDEX.md'), 'utf8'), /Fixture page/);
  assert.equal(fs.readFileSync(f.target('reference/projects.md')).equals(old), true);
  assert.equal(fs.readFileSync(f.target('references.md')).equals(navigation), true);
});

for (const command of ['archive', 'unarchive']) test('reference index ' + command + ' preserves page bytes through the real CLI', async t => {
  const f = await fixture(t);
  const from = 'reference/projects/' + (command === 'unarchive' ? 'archive/' : '') + 'topic.md';
  const to = 'reference/projects/' + (command === 'archive' ? 'archive/' : '') + 'topic.md';
  f.write(from, page);
  const result = await f.run([command, '--path', from], { stdin: '' });
  assert.equal(result.status, 0, JSON.stringify(result));
  assert.equal(JSON.parse(result.stdout).path, to);
  assert.equal(fs.existsSync(f.target(from)), false);
  assert.equal(fs.readFileSync(f.target(to), 'utf8'), page);
  assert.match(fs.readFileSync(f.target(path.posix.dirname(to) + '/INDEX.md'), 'utf8'), /Fixture page/);
});

test('reference index rejects unsupported commands and argument shapes with usable guidance', async t => {
  const f = await fixture(t);
  const requests = [
    [], ['create', '--path', 'reference/projects/new.md'], ['move-old'], ['delete'],
    ['rebuild', '--path', 'reference/projects/topic.md'], ['archive'], ['unarchive'],
    ['archive', '--path'], ['archive', '--path', ''], ['archive', '--path', '--root'],
    ['archive', 'reference/projects/topic.md'], ['archive', '--path=reference/projects/topic.md'],
    ['archive', '--path', 'reference/projects/topic.md', '--path', 'reference/projects/other.md'],
    ['unarchive', '--path', 'reference/projects/archive/topic.md', 'extra'],
    ['rebuild', '--root', f.outside], ['rebuild', null], 'rebuild', null,
  ];
  for (const args of requests) {
    const result = await f.run(args);
    assert.equal(result.ok, false);
    assert.equal(result.code, 'TOOL_PROTOCOL_ERROR');
    assert.match(result.message, /reference-index expects rebuild, archive --path.*unarchive --path/);
  }
  assert.equal(fs.existsSync(f.target('reference/projects/INDEX.md')), false);
  assert.equal(f.trace.length, requests.length);
});

test('reference index refuses stdin and request-level environment or root overrides', async t => {
  const f = await fixture(t);
  for (const extra of [{ stdin: 'create this content' }, { stdin: 1 },
    { env: { ZYLOS_DIR: f.outside } }, { root: f.outside }, { cwd: f.outside }, { ZYLOS_DIR: f.outside }]) {
    const result = await f.run(['rebuild'], extra);
    assert.equal(result.ok, false);
    assert.match(result.message, /no extra arguments, stdin, or environment overrides/);
  }
  assert.equal(fs.readdirSync(f.outside).length, 0);
  assert.equal(fs.existsSync(f.target('reference/projects/INDEX.md')), false);
  const result = await f.run(['rebuild']);
  assert.equal(result.status, 0, JSON.stringify(result));
  assert.equal(fs.readdirSync(f.outside).length, 0);
  assert.equal(fs.existsSync(f.target('reference/projects/INDEX.md')), true);
});

test('reference index retains the real CLI path and symlink protections', async t => {
  const f = await fixture(t);
  const foreign = path.join(f.outside, 'topic.md');
  fs.writeFileSync(foreign, page);
  f.write('reference/projects/topic.md', page);
  fs.symlinkSync(foreign, f.target('reference/projects/link.md'));
  for (const requested of [foreign, '../topic.md', 'reference/projects/../topic.md',
    'reference/projects/link.md', 'reference/projects/archive/topic.md']) {
    const result = await f.run(['archive', '--path', requested]);
    assert.equal(result.status, 1, JSON.stringify(result));
    assert.match(result.stderr, /PATH_NOT_ALLOWED/);
  }
  assert.equal(fs.readFileSync(foreign, 'utf8'), page);
  assert.equal(fs.readFileSync(f.target('reference/projects/topic.md'), 'utf8'), page);
  assert.equal(fs.readdirSync(f.outside).length, 1);
});
