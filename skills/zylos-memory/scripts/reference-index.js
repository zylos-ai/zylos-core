#!/usr/bin/env node
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomBytes } from 'node:crypto';
import { isSelfPath, resolveAllowedMemoryPath } from './self-write.js';
import { helpRequested, inputError, memoryError, options, runCli } from './sync-cli.js';
import { isMainModule } from './is-main-module.js';

const statuses = { projects: ['active', 'planning', 'paused', 'completed', 'abandoned'], decisions: ['active', 'archived'] };
// The 48-character limit includes the .md extension.
const pageName = name => /^[a-z0-9-]+\.md$/.test(name) && name.length <= 48;
const pagePath = (relative, archived = false) => {
  const parts = relative.split('/');
  return parts[0] === 'reference' && Object.hasOwn(statuses, parts[1]) &&
    (archived ? parts.length === 4 && parts[2] === 'archive' : parts.length === 3) && pageName(parts.at(-1));
};
const exists = target => {
  try { fs.lstatSync(target); return true; }
  catch (error) { if (error.code === 'ENOENT') return false; throw error; }
};
const unused = target => { if (exists(target)) throw memoryError('EXISTS', 'Target already exists'); };
const temporaryPath = target => path.join(path.dirname(target), `.${path.basename(target)}.${randomBytes(16).toString('hex')}.tmp`);

function moveWithoutOverwrite(source, target) {
  try { fs.linkSync(source, target); }
  catch (error) { if (error.code === 'EEXIST') throw memoryError('EXISTS', 'Target already exists'); throw error; }
  // If removal fails, retain both copies rather than roll back published data.
  try { fs.unlinkSync(source); }
  catch (error) { error.message = `Destination was published but source removal failed: ${error.message}`; throw error; }
}

function publish(target, content, create = false) {
  fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  const temporary = temporaryPath(target);
  try {
    fs.writeFileSync(temporary, content, { flag: 'wx', mode: 0o600 });
    if (create) {
      try { fs.linkSync(temporary, target); }
      catch (error) { if (error.code === 'EEXIST') throw memoryError('EXISTS', 'Target already exists'); throw error; }
    } else fs.renameSync(temporary, target);
  } finally {
    try { fs.unlinkSync(temporary); } catch {}
  }
}

function header(text, kind) {
  const block = text.split(/\r?\n\s*\r?\n/, 1)[0].split(/\r?\n/);
  const title = /^# (\S.*)$/.exec(block[0])?.[1];
  const fields = {};
  for (const line of block.slice(1)) {
    const match = /^- \*\*(Status|Updated|Keys|Scope):\*\* (.*)$/.exec(line);
    if (match) {
      fields[match[1]] = match[2];
    }
  }
  if (!title || !block.includes(`<!-- zylos:entry kind=${kind} -->`) ||
      !statuses[kind].includes(fields.Status) || !/^\d{4}-\d{2}-\d{2}$/.test(fields.Updated ?? '') ||
      !Number.isFinite(Date.parse(fields.Updated)) || new Date(fields.Updated).toISOString().slice(0, 10) !== fields.Updated) return null;
  return { title, ...fields };
}
const cell = text => (text ?? '').replaceAll('|', '／');

function indexText(root, kind, archived) {
  const directory = `reference/${kind}${archived ? '/archive' : ''}`;
  const target = resolveAllowedMemoryPath({ root, path: `${directory}/INDEX.md`, allowed: p => p === `${directory}/INDEX.md` }).target;
  fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  const pages = [], malformed = [];
  for (const entry of fs.readdirSync(path.dirname(target), { withFileTypes: true })) {
    if (!entry.isFile() || entry.name.startsWith('.') || entry.name === 'INDEX.md' || !entry.name.endsWith('.md')) continue;
    const parsed = header(fs.readFileSync(path.join(path.dirname(target), entry.name), 'utf8'), kind);
    if (parsed) pages.push({ ...parsed, file: entry.name }); else malformed.push(entry.name);
  }
  pages.sort((a, b) => statuses[kind].indexOf(a.Status) - statuses[kind].indexOf(b.Status) ||
    b.Updated.localeCompare(a.Updated) || a.file.localeCompare(b.file));
  const label = kind === 'projects' ? 'Projects' : 'Decisions';
  const navigation = archived
    ? `Current ${kind}: ../INDEX.md.`
    : `Archived ${kind}: archive/INDEX.md. If a ${kind === 'projects' ? 'project' : 'topic'} is not listed, Grep reference/${kind}/ (including archive/), then the old ${kind}.md or reference/legacy/.`;
  const lines = [`# ${archived ? 'Archived ' : ''}${label} Index`,
    `<!-- zylos:index kind=${kind} v=1 — generated by reference-index.js rebuild; edit the page headers instead -->`, navigation, '',
    `| Status | Updated | ${kind === 'projects' ? 'Project' : 'Topic'} | File | ${kind === 'projects' ? 'Keys' : 'Scope'} |`,
    '|---|---|---|---|---|'];
  for (const row of pages) lines.push(`| ${row.Status} | ${row.Updated} | ${cell(row.title)} | ${cell(row.file)} | ${cell(row[kind === 'projects' ? 'Keys' : 'Scope'])} |`);
  if (malformed.length) lines.push('', '## Unparsable page headers', '', ...malformed.sort().map(file => `- ${cell(file)}`));
  return { target, content: lines.join('\n') + '\n' };
}

export function rebuild(root) {
  for (const kind of Object.keys(statuses)) for (const archived of [false, true]) {
    const { target, content } = indexText(root, kind, archived);
    publish(target, content);
  }
  return { ok: true };
}

export function createPage(root, requested, content) {
  const permitted = p => pagePath(p);
  if (!permitted(requested)) throw memoryError('PATH_NOT_ALLOWED', 'Expected a direct reference page path');
  const { target } = resolveAllowedMemoryPath({ root, path: requested, allowed: permitted });
  publish(target, content, true);
  return { ok: true, path: requested, bytes: Buffer.byteLength(content) };
}

export function movePage(root, requested, unarchive = false) {
  if (!pagePath(requested, unarchive)) throw memoryError('PATH_NOT_ALLOWED', 'Expected a reference page path');
  const source = resolveAllowedMemoryPath({ root, path: requested, allowed: p => pagePath(p, unarchive) }).target;
  const destination = unarchive ? requested.replace('/archive/', '/') : requested.replace(/\/([^/]+)$/, '/archive/$1');
  const target = resolveAllowedMemoryPath({ root, path: destination, allowed: p => pagePath(p, !unarchive) }).target;
  fs.mkdirSync(path.dirname(target), { recursive: true, mode: 0o700 });
  moveWithoutOverwrite(source, target);
  rebuild(root);
  return { ok: true, path: destination };
}

export function moveOld(root, now = new Date()) {
  const pad = value => String(value).padStart(2, '0');
  const stamp = `${now.getFullYear()}${pad(now.getMonth() + 1)}${pad(now.getDate())}-${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
  const moves = [];
  for (const name of ['projects', 'decisions']) {
    const old = `reference/${name}.md`, archived = `reference/legacy/${name}-before-split-${stamp}.md`;
    const source = resolveAllowedMemoryPath({ root, path: old, allowed: p => p === old }).target;
    if (!exists(source)) continue;
    const target = resolveAllowedMemoryPath({ root, path: archived, allowed: p => p === archived }).target;
    unused(target);
    moves.push({ source, target, path: archived });
  }
  for (const move of moves) {
    fs.mkdirSync(path.dirname(move.target), { recursive: true, mode: 0o700 });
    moveWithoutOverwrite(move.source, move.target);
  }
  return { ok: true, paths: moves.map(move => move.path) };
}

// Shared pages include archived topics; legacy sources and generated indexes are history.
export function checkNavigation(root) {
  const memory = path.resolve(root, 'memory');
  const navigation = [], headings = [];
  const inspect = (relative, text) => {
    for (const [index, line] of text.split(/\r?\n/).entries()) {
      const oldPaths = [...line.matchAll(/(?<![\w.-])(?:[~\w./-]*\/)?(?:projects|decisions)\.md(?=$|[^\w./-])/g)]
        .filter(match => !/(?:^|\/)(?:legacy|archive)\//.test(match[0]));
      const location = { path: relative, line: index + 1, text: line };
      if (relative === 'references.md' && oldPaths.length) navigation.push(location);
      if (oldPaths.length) headings.push(location);
    }
  };
  const visit = relative => {
    const lexical = path.join(memory, relative);
    let stat;
    try { stat = fs.lstatSync(lexical); } catch (error) { if (error.code === 'ENOENT') return; throw error; }
    if (stat.isSymbolicLink()) throw memoryError('PATH_NOT_ALLOWED', 'Navigation checks do not follow symlinks');
    const target = resolveAllowedMemoryPath({ root, path: relative,
      allowed: p => p === 'reference' || p === 'users' || isSelfPath(p) }).target;
    if (stat.isDirectory()) {
      for (const entry of fs.readdirSync(target, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
        if (entry.name.startsWith('.')) continue;
        if (relative === 'reference' && entry.name === 'legacy') continue;
        if (entry.name === 'INDEX.md' && /^reference\/(projects|decisions)(\/archive)?$/.test(relative)) continue;
        if (relative === 'reference' && ['projects.md', 'decisions.md'].includes(entry.name)) continue;
        visit(`${relative}/${entry.name}`);
      }
    } else if (stat.isFile() && relative.endsWith('.md')) inspect(relative, fs.readFileSync(target, 'utf8'));
  };
  for (const relative of ['identity.md', 'references.md', 'reference', 'users']) visit(relative);
  return { navigation: { count: navigation.length, locations: navigation }, headings: { count: headings.length, locations: headings } };
}

if (isMainModule(import.meta.url)) await runCli(() => {
  if (helpRequested(process.argv.slice(2), ['path'])) {
    console.log('Usage: reference-index.js rebuild | check-navigation | create --path PATH < content | archive --path PATH | unarchive --path PATH | move-old');
    return;
  }
  const [command, ...argv] = process.argv.slice(2);
  const args = options(argv, ['path']);
  if (args.positional.length || !['rebuild', 'check-navigation', 'create', 'archive', 'unarchive', 'move-old'].includes(command) ||
      (['create', 'archive', 'unarchive'].includes(command) ? !args.path : args.path !== undefined)) throw inputError('Expected rebuild, create --path, archive --path, unarchive --path, or move-old');
  const root = process.env.ZYLOS_DIR || path.join(os.homedir(), 'zylos');
  const result = command === 'check-navigation' ? checkNavigation(root) : command === 'rebuild' ? rebuild(root) : command === 'create' ? createPage(root, args.path, fs.readFileSync(0)) :
    command === 'move-old' ? moveOld(root) : movePage(root, args.path, command === 'unarchive');
  console.log(JSON.stringify(result));
});
