// Development-only build. Runtime consumes the checked-in generated module.
import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { pathToFileURL, fileURLToPath } from 'node:url';
const modules = process.env.REDACTION_BUILD_MODULE_DIR;
const dependency = (name) =>
  modules
    ? pathToFileURL(
        path.join(modules, name, name === 'smol-toml' ? 'dist/index.js' : 'rewrite-pattern.js'),
      ).href
    : name;
const { parse } = await import(dependency('smol-toml'));
const { default: rewrite } = await import(dependency('regexpu-core'));
const root = fileURLToPath(new URL('../src/lib/redaction/', import.meta.url));
const POSIX = {
  alnum: 'a-zA-Z0-9',
  alpha: 'a-zA-Z',
  digit: '0-9',
  lower: 'a-z',
  upper: 'A-Z',
  space: '\\t\\n\\v\\f\\r ',
  xdigit: '0-9A-Fa-f',
  word: '\\w',
  punct: '!-\\/:-@\\[-`{-~',
};

// Find index of the ')' closing the group that contains position p (or -1 = end of pattern).
function enclosingGroupEnd(src, p) {
  let depth = 0;
  let inClass = false;
  for (let i = p; i < src.length; i++) {
    const c = src[i];
    if (c === '\\') {
      i++;
      continue;
    }
    if (inClass) {
      if (c === ']') inClass = false;
      continue;
    }
    if (c === '[') {
      inClass = true;
      if (src[i + 1] === '^') i++;
      if (src[i + 1] === ']') i++;
      continue;
    }
    if (c === '(') depth++;
    else if (c === ')') {
      if (depth === 0) return i;
      depth--;
    }
  }
  return -1;
}

function re2ToJs(src) {
  let flags = '';
  let s = src;
  // leading global flags
  const lead = s.match(/^\(\?([ims]+)\)/);
  if (lead) {
    flags += lead[1].replace('m', 'm');
    s = s.slice(lead[0].length);
  }
  s = s.replace(/\(\?P</g, '(?<');
  s = s.replace(/\[:(\w+):\]/g, (m, n) => POSIX[n] ?? m);
  s = s.replace(/(^|[^\\])((?:\\\\)*)\\z/g, '$1$2$');
  s = s.replace(/(^|[^\\])((?:\\\\)*)\\A/g, '$1$2^');
  // mid-pattern (?i) -> (?i: ... ) up to end of enclosing group
  let idx;
  while ((idx = s.indexOf('(?i)')) !== -1) {
    const end = enclosingGroupEnd(s, idx + 4);
    if (end === -1) s = s.slice(0, idx) + '(?i:' + s.slice(idx + 4) + ')';
    else s = s.slice(0, idx) + '(?i:' + s.slice(idx + 4, end) + ')' + s.slice(end);
  }
  return { source: s, flags };
}

function compile(regex) {
  let { source, flags } = re2ToJs(regex);
  let previous;
  do {
    previous = source;
    source = source
      .replace(/^\[\\w\.-\]\{0,50\}\?/, '')
      .replace(/^\(\?i:\[\\w\.-\]\{0,50\}\?/, '(?i:');
  } while (source !== previous);
  if (/\(\?[ims-]+:/.test(source)) {
    if (flags.includes('i')) {
      source = `(?i:${source})`;
      flags = flags.replace('i', '');
    }
    source = rewrite(source, flags, { modifiers: 'transform' });
  }
  new RegExp(source, flags + 'gd');
  return { regex: source, flags };
}
function allowlist(a) {
  return {
    condition: (a.condition || 'OR').toUpperCase(),
    regexTarget: a.regexTarget || 'secret',
    regexes: (a.regexes || []).map(compile),
    stopwords: a.stopwords || [],
  };
}
const main = fs.readFileSync(path.join(root, 'vendor/gitleaks.toml'), 'utf8');
const extra = fs.readFileSync(path.join(root, 'vendor/betterleaks-extra.toml'), 'utf8');
const g = parse(main),
  b = parse(extra);
const rules = [];
for (const rule of [...g.rules, ...b.rules]) {
  if (!rule.regex) continue;
  let entropy = rule.entropy;
  if (rule.filter) {
    const m = /^entropy\(finding\["secret"\]\) <= ([\d.]+)\s*$/.exec(rule.filter);
    if (!m) throw new Error(`Unsupported Betterleaks filter in ${rule.id}`);
    entropy = Number(m[1]);
  }
  rules.push({
    id: rule.id,
    label: rule.id
      .split('-')
      .map((s) => (s === 'api' ? 'API' : s[0].toUpperCase() + s.slice(1)))
      .join(' '),
    ...compile(rule.regex),
    entropy,
    secretGroup: rule.secretGroup,
    keywords: rule.keywords || [],
    allowlists: (rule.allowlists || []).map(allowlist),
  });
}
const version = createHash('sha256').update(main).update(extra).digest('hex').slice(0, 16);
fs.writeFileSync(
  path.join(root, 'rules.generated.js'),
  `// Generated by scripts/build-redaction-rules.js; do not edit.\nexport const RULE_VERSION = ${JSON.stringify(version)};\nexport const globalAllowlist = ${JSON.stringify([allowlist(g.allowlist || {})])};\nexport const rules = ${JSON.stringify(rules, null, 2)};\n`,
);
console.log(
  `Built ${rules.length} text rules (${g.rules.length} gitleaks definitions + ${b.rules.length} selected Betterleaks rules).`,
);
