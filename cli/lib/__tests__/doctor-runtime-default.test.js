import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import dns from 'node:dns/promises';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

test('doctor resolves actual instance configuration and uses the Antigravity adapter for a rejected key', async t => {
  const root = process.env.ZYLOS_DIR, bin = path.join(root, 'bin');
  fs.mkdirSync(bin, { recursive: true }); fs.mkdirSync(path.join(root, '.zylos'), { recursive: true });
  fs.writeFileSync(path.join(root, '.zylos/config.json'), JSON.stringify({ session_mode: 'single', runtime: 'agy' }));
  fs.writeFileSync(path.join(root, '.env'), `GEMINI_API_KEY=invalid-fixture-key\nTZ=Asia/Singapore\nZYLOS_TMUX_PATH_PREPEND=${bin}\n`);
  fs.symlinkSync('/usr/bin/which', path.join(bin, 'which'));
  fs.writeFileSync(path.join(bin, 'tmux'), `#!${process.execPath}\nconsole.error('no server running'); process.exit(1);`, { mode: 0o755 });
  fs.writeFileSync(path.join(bin, 'agy'), `#!${process.execPath}\nconsole.log('1.5.11');`, { mode: 0o755 });
  fs.writeFileSync(path.join(bin, 'curl'), `#!${process.execPath}\nprocess.stdin.resume(); process.stdin.on('end',()=>process.stdout.write('401'));`, { mode: 0o755 });
  const savedPath = process.env.PATH; process.env.PATH = bin;
  t.after(() => { process.env.PATH = savedPath; });
  t.mock.method(dns, 'resolve4', async () => ['127.0.0.1']);
  const { collectDiagnostics, buildDiagnosticJson } = await import('../../commands/doctor.js');
  const options = { pm2Check: () => ({ installed: false }), tmuxCheck: () => ({ installed: false }), psCheck: () => ({ available: true }), modeStatus: () => null };
  const json = buildDiagnosticJson(await collectDiagnostics(new Map(), options), { success: true, version: 'fixture' });
  assert.equal(json.runtime, 'agy'); assert.equal(json.display, 'Antigravity');
  assert.equal(json.groups.system.checks.network.host, 'generativelanguage.googleapis.com');
  assert.equal(json.groups.ai_service.checks.auth.status, 'failure');
  assert.match(json.issues.find(row => row.id === 'cli_not_authed').hint, /--save-apikey/);
  fs.mkdirSync(path.join(root, '.claude/skills'), { recursive: true });
  fs.writeFileSync(path.join(root, '.zylos/components.json'), '{}');
  const run = spawnSync(process.execPath, [fileURLToPath(new URL('../../zylos.js', import.meta.url)), 'doctor', '--json'], { env: process.env, encoding: 'utf8', timeout: 20000 });
  assert.equal(run.status, 1);
  const commandJson = JSON.parse(run.stdout);
  assert.equal(commandJson.display, 'Antigravity');
  assert.equal(commandJson.groups.system.checks.network.host, 'generativelanguage.googleapis.com');
  assert.equal(commandJson.issues.some(row => /Claude|Autonomous/.test(row.label)), false);
  fs.writeFileSync(path.join(root, '.zylos/config.json'), JSON.stringify({ session_mode: 'single', runtime: 'future' }));
  const unknown = await collectDiagnostics(new Map(), options);
  assert.equal(unknown.runtime, 'future');
  assert.match(buildDiagnosticJson(unknown, { success: true }).issues.find(row => row.id === 'runtime_unknown').hint, /does not provide diagnostics/);
});
