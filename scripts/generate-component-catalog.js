#!/usr/bin/env node
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { createCatalogArtifacts } from '../skills/comm-bridge/scripts/c4-component-catalog.js';

export const GENERATED_START = '// BEGIN GENERATED COMPONENT CATALOG';
export const GENERATED_END = '// END GENERATED COMPONENT CATALOG';

/** Derive shared validation cases at build/test time, never in the browser payload. */
export function createComponentFixtures(artifacts = createCatalogArtifacts()) {
  const clone = value => JSON.parse(JSON.stringify(value));
  return {
    valid: artifacts.COMPONENT_DEFINITIONS.map(component => ({ key: component.key, envelope: clone(component.example) })),
    invalid: artifacts.COMPONENT_DEFINITIONS.map(component => {
      const envelope = clone(component.example);
      envelope.blocks[0].data.unrecognized = true;
      return { key: component.key, envelope };
    }),
  };
}

export function renderGeneratedRegion(artifacts = createCatalogArtifacts()) {
  return [GENERATED_START, '// Generated by scripts/generate-component-catalog.js; edit c4-component-catalog.js.',
    ...Object.entries(artifacts).map(([key, value]) => `export const ${key} = ${JSON.stringify(value)};`),
    'const blockTypes = BLOCK_SCHEMA.properties.type.enum;',
    'const interactive = COMPONENT_DEFINITIONS.filter(component => component.interactive).map(component => component.type);',
    GENERATED_END].join('\n');
}

export function updateSchemaSource(source, artifacts = createCatalogArtifacts()) {
  const start = source.indexOf(GENERATED_START), end = source.indexOf(GENERATED_END);
  if (start < 0 || end < start || source.indexOf(GENERATED_START, start + 1) >= 0
    || source.indexOf(GENERATED_END, end + 1) >= 0) throw new Error('Missing or ambiguous generated catalog markers');
  return source.slice(0, start) + renderGeneratedRegion(artifacts) + source.slice(end + GENERATED_END.length);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    console.error('Usage: node scripts/generate-component-catalog.js [--check]');
    process.exitCode = 1;
  } else {
    const file = new URL('../skills/comm-bridge/scripts/c4-content-schema.js', import.meta.url);
    const current = fs.readFileSync(file, 'utf8'), generated = updateSchemaSource(current);
    if (args[0] === '--check') {
      if (current !== generated) {
        console.error('Component catalog data is stale; run node scripts/generate-component-catalog.js');
        process.exitCode = 1;
      }
    } else if (current !== generated) fs.writeFileSync(file, generated);
  }
}
